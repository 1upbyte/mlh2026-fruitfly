"""## 4. Load the whole brain
Three files, no token needed:
- **neurons**: every neuron's ID
- **wiring**: every connection, as +synapses (excites) or −synapses (inhibits)
- **labels**: what each neuron is (sugar taste, escape, ...)
"""

import pandas as pd, numpy as np, scipy.sparse as sp

SHIU = "https://github.com/philshiu/Drosophila_brain_model/raw/main/"
neurons = pd.read_csv(SHIU + "Completeness_783.csv", index_col=0)
wiring = pd.read_parquet(SHIU + "Connectivity_783.parquet")
labels = pd.read_csv("https://github.com/flyconnectome/flywire_annotations/raw/main/supplemental_files/"
                     "Supplemental_file1_neuron_annotations.tsv", sep="\t", low_memory=False)

N = len(neurons)
W = sp.csr_matrix((wiring["Excitatory x Connectivity"],
                   (wiring["Presynaptic_Index"], wiring["Postsynaptic_Index"])), shape=(N, N))
row = {root_id: i for i, root_id in enumerate(neurons.index)}

def find(mask):
    """Neurons matching a label filter -> their row numbers in W."""
    return np.array([row[r] for r in labels.root_id[mask] if r in row])

print(f"{N:,} neurons, {W.nnz:,} connections")

"""## 5. Pick the neurons we care about
| Group | What it does |
|---|---|
| sugar | taste cells on the mouth that detect sugar |
| bitter | taste cells that detect bitter |
| looming | eye cells that see something rushing at you |
| mn9 | motor neuron that sticks the mouth out to **eat** |
| giant_fibre | the **escape** jump command |
| mdn | makes the fly **walk backwards** |

Want others? Browse names at **https://codex.flywire.ai** and filter `labels` the same way.
"""

sugar       = find(labels.cell_type == "LB3c")
bitter      = find(labels.cell_sub_class == "bitter")
looming     = find(labels.cell_type.isin(["LC4", "LPLC2"]))
giant_fibre = find(labels.cell_type == "DNp01")
mdn         = find(labels.cell_type == "MDN")
mn9         = np.array([row[720575940660219265]])  # not in the label file; ID from Shiu et al. 2024

for name in ["sugar", "bitter", "looming", "mn9", "giant_fibre", "mdn"]:
    print(f"{name:12s} {len(globals()[name]):4d} neurons")

"""## 6. The simulator
Every neuron is a tiny voltage meter. Incoming spikes push it up (or down, if inhibitory), it leaks back toward rest, and when it crosses a threshold it **spikes** and passes that on. Settings come from [Shiu et al. 2024](https://www.nature.com/articles/s41586-024-07763-9).

You don't need to read this code. Just run it.
"""

def simulate(inputs, ms=200, W=W, seed=0):
    """inputs: [(neurons, rate_hz), ...]  ->  spike count for every neuron."""
    dt, v0, vth, tm, ts, ref = 0.1, -52.0, -45.0, 20.0, 5.0, 2.2
    wsyn, kick, delay = 0.275, 250 * 0.275, int(1.8 / 0.1)
    rng = np.random.default_rng(seed)
    v, g = np.full(N, v0), np.zeros(N)
    last, counts = np.full(N, -1e9), np.zeros(N, int)
    driven = np.zeros(N, bool)
    for idx, _ in inputs:
        driven[idx] = True
    ring = np.zeros((delay, N))
    for k in range(int(ms / dt)):
        t, slot = k * dt, k % delay
        g += ring[slot]; ring[slot] = 0
        free = ((t - last) > ref) | driven
        v[free] += dt * (v0 - v[free] + g[free]) / tm
        g[free] *= np.exp(-dt / ts)
        for idx, hz in inputs:
            v[idx[rng.random(len(idx)) < hz * dt / 1000]] += kick
        s = np.flatnonzero(v > vth)
        v[s], g[s], last[s] = v0, 0.0, t
        counts[s] += 1
        if len(s):
            ring[slot] += np.asarray(W[s].sum(0)).ravel() * wsyn
    return counts

def rate(counts, group, ms=200):
    """Average spikes per second of a group."""
    return counts[group].sum() / len(group) / (ms / 1000)

"""## 7. Poke the brain 🧪
Feed it sugar, bitter and a scary looming shadow, and watch what it decides. Each run is 0.2 s of brain time and takes a few seconds.

**What you should see:**
- nothing in → nothing out
- sugar → it wants to **eat** (mn9 fires)
- sugar + bitter → it changes its mind
- looming → it **escapes** (giant_fibre fires)
"""

experiments = {
    "nothing":        [],
    "sugar":          [(sugar, 200)],
    "sugar + bitter": [(sugar, 200), (bitter, 200)],
    "looming":        [(looming, 150)],
}
results = []
for name, inputs in experiments.items():
    c = simulate(inputs)
    results.append({"experiment": name, "eat (mn9 Hz)": rate(c, mn9),
                    "escape (giant_fibre Hz)": rate(c, giant_fibre),
                    "back up (mdn Hz)": rate(c, mdn), "neurons active": int((c > 0).sum())})
results = pd.DataFrame(results)
results

